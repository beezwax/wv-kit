import fs from 'node:fs';
import path from 'node:path';

// `wv-kit migrate` — non-destructive. Inspects the cwd, writes a
// WV-KIT-MIGRATION.md brief tailored to "convert this project to wv-kit",
// and exits. The user then opens an AI agent (Claude Code, etc.) in the
// directory and asks it to perform the migration; the markdown is the
// full brief.
//
// Scope is deliberately minimal: read package.json + a shallow scan of
// src/. No grep, no AST, no source edits. Anything subtler is left for
// the agent — who reads the actual code — to figure out.

export function runMigrate() {
  const cwd = process.cwd();
  const detected = detectProject(cwd);
  const outPath = path.join(cwd, 'WV-KIT-MIGRATION.md');
  fs.writeFileSync(outPath, renderMigrationDoc(detected));

  console.log('');
  console.log(`Wrote ${path.relative(cwd, outPath)}`);
  console.log('');
  console.log('Detected:');
  console.log(`  framework: ${detected.framework}`);
  console.log(`  language:  ${detected.typescript ? 'TypeScript' : 'JavaScript'}`);
  if (detected.srcEntries.length) {
    console.log(`  src/:      ${detected.srcEntries.join(', ')}`);
  } else {
    console.log(`  src/:      (none found)`);
  }
  console.log('');
  console.log('Next: open an AI agent (e.g. Claude Code) in this directory and say:');
  console.log('  "Perform the migration described in WV-KIT-MIGRATION.md."');
  console.log('');
}

function detectProject(cwd) {
  const pkgPath = path.join(cwd, 'package.json');
  let pkg = null;
  if (fs.existsSync(pkgPath)) {
    try { pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8')); }
    catch { pkg = null; }
  }
  const deps = { ...(pkg?.dependencies ?? {}), ...(pkg?.devDependencies ?? {}) };

  const framework =
    'kensington' in deps ? 'kensington' :
    'svelte'     in deps ? 'svelte'     :
    'solid-js'   in deps ? 'solid'      :
    'lit'        in deps ? 'lit'        :
    'react'      in deps ? 'react'      :
    'plain-js';

  const typescript =
    fs.existsSync(path.join(cwd, 'tsconfig.json')) ||
    'typescript' in deps;

  let srcEntries = [];
  let srcHasSubdirs = false;
  const srcDir = path.join(cwd, 'src');
  if (fs.existsSync(srcDir) && fs.statSync(srcDir).isDirectory()) {
    srcEntries = fs.readdirSync(srcDir).sort();
    srcHasSubdirs = srcEntries.some(e => {
      try { return fs.statSync(path.join(srcDir, e)).isDirectory(); }
      catch { return false; }
    });
  }

  // Top-level cwd directories that aren't obviously infrastructure. Surfacing
  // these forces the migration agent to address project-specific layout —
  // home-grown dev servers, mock-data trees, separate `app/` dirs, etc.
  const skipTopLevel = new Set(['node_modules', '.git', 'dist', 'build', 'src', 'fm', 'public', '.vscode', '.idea']);
  let topLevelDirs = [];
  try {
    topLevelDirs = fs.readdirSync(cwd)
      .filter(name => !name.startsWith('.') && !skipTopLevel.has(name))
      .filter(name => {
        try { return fs.statSync(path.join(cwd, name)).isDirectory(); }
        catch { return false; }
      })
      .sort();
  } catch { topLevelDirs = []; }

  return {
    name: pkg?.name ?? path.basename(cwd),
    pkgExists: !!pkg,
    framework,
    typescript,
    srcEntries,
    srcHasSubdirs,
    topLevelDirs,
    wvKitAlreadyInstalled: 'wv-kit' in deps,
    hasViteConfig: hasAny(cwd, ['vite.config.js', 'vite.config.ts', 'vite.config.mjs']),
    hasEslintConfig: hasAny(cwd, ['eslint.config.js', 'eslint.config.mjs', '.eslintrc', '.eslintrc.json', '.eslintrc.js']),
    hasTsconfig: fs.existsSync(path.join(cwd, 'tsconfig.json')),
    hasFmDir: fs.existsSync(path.join(cwd, 'fm')),
    existingScripts: pkg?.scripts ?? {},
  };
}

function hasAny(cwd, names) {
  return names.some(n => fs.existsSync(path.join(cwd, n)));
}

