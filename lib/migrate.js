function frameworkDepLines(framework) {
  switch (framework) {
    case 'react':      return ',\n"react": "^19.0.0",\n"react-dom": "^19.0.0"';
    case 'svelte':     return ',\n"svelte": "^5.0.0",\n"@sveltejs/vite-plugin-svelte": "^7.0.0"';
    case 'solid':      return ',\n"solid-js": "^1.9.5"';
    case 'lit':        return ',\n"lit": "^3.2.1"';
    case 'kensington': return ',\n"kensington": "^2.0.0-signals.15"';
    default:           return '';
  }
}

function viteConfigSnippet(framework) {
  if (framework === 'react') {
    return `import react from '@vitejs/plugin-react';
import { mergeConfig } from 'vite';
import baseConfig from 'wv-kit/vite.config.js';

export default mergeConfig(baseConfig, { plugins: [react()] });`;
  }
  if (framework === 'solid') {
    return `import solid from 'vite-plugin-solid';
import { mergeConfig } from 'vite';
import baseConfig from 'wv-kit/vite.config.js';

export default mergeConfig(baseConfig, { plugins: [solid()] });`;
  }
  if (framework === 'svelte') {
    return `import { svelte, vitePreprocess } from '@sveltejs/vite-plugin-svelte';
import { mergeConfig } from 'vite';
import baseConfig from 'wv-kit/vite.config.js';

export default mergeConfig(baseConfig, {
  plugins: [svelte({ preprocess: vitePreprocess() })],
});`;
  }
  return `import { mergeConfig } from 'vite';
import baseConfig from 'wv-kit/vite.config.js';

export default mergeConfig(baseConfig, {});`;
}
